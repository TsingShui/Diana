package yy;

public class g {
    public static int marker(int x) {
        return Integer.reverseBytes(x);
    }

    public static int read(int x) {
        return Integer.highestOneBit(h.n(x));
    }

    public static int write(int x) {
        return Integer.numberOfLeadingZeros(h.n(x));
    }
}
